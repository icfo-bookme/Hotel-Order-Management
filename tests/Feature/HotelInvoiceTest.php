<?php

namespace Tests\Feature;

use App\Models\ShipTicketSale;
use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

class HotelInvoiceTest extends TestCase
{
    use RefreshDatabase;

    public function test_sale_returns_a_printable_customer_invoice_without_partner_financials(): void
    {
        $user = User::factory()->create();
        $sale = ShipTicketSale::create(['customer_name' => '<script>alert(1)</script>', 'customer_mobile' => '01712345678', 'ship_id' => 1, 'ticket_fee' => 100, 'received_amount' => 100, 'issued_date' => '2026-10-19']);
        $data = ['rooms' => [[
            'hotel_name' => 'Ocean Hotel', 'bookme_hotel_id' => 523, 'room_name' => 'Deluxe',
            'check_in_date' => '2026-10-20', 'check_out_date' => '2026-10-22',
            'customer_price_per_night' => '5000.15', 'partner_price_per_night' => '4000.10',
        ]], 'hotel_advances' => [['bookme_hotel_id' => 523, 'amount' => '3000.25']],
            'payments' => [['amount' => '3000.25', 'other_fee' => '111.99', 'payment_method' => 'bkash', 'paid_at' => now()->toDateTimeString(), 'transaction_reference' => 'INV-123']],
        ];
        $response = $this->actingAsAdmin($user)->postJson(route('hotel-sales.sell', $sale), $data)->assertCreated();
        $id = $response->json('data.id');
        $url = route('hotel-bookings.invoice', $id);
        $response->assertJsonPath('invoice_url', $url);
        $this->get($url)->assertOk()->assertSee('BookMe Travel Agency')->assertSee('BM-HB-000001')->assertSee('bookme-logo.png')->assertSee('Ocean Hotel')->assertSee('Deluxe')->assertSee('10000.30')->assertSee('3000.25')->assertSee('7000.05')->assertDontSee('<th>Status</th>', false)->assertSee('support@bookme.com.bd')->assertSee('Generated by:')->assertSee('No signature required.')->assertSee('<script>alert(1)</script>')->assertDontSee('<script>alert(1)</script>', false)->assertDontSee('4000.10')->assertDontSee('B2B')->assertDontSee('111.99');
        $booking = \App\Models\HotelBooking::findOrFail($id);
        $booking->rooms()->first()->reschedules()->create(['old_check_in_date' => '2026-10-18', 'old_check_out_date' => '2026-10-20', 'new_check_in_date' => '2026-10-20', 'new_check_out_date' => '2026-10-22', 'customer_fee' => '500', 'partner_fee' => '100', 'reason' => 'Changed dates', 'created_by' => $user->id]);
        $rejected = $booking->payments()->create(['amount' => '2000', 'payment_method' => 'cash', 'paid_at' => now()]);
        $rejected->forceFill(['status' => 'rejected'])->save();
        $this->get($url)->assertOk()->assertSee('Reschedule charges')->assertSee('10500.30')->assertSee('7500.05')->assertDontSee('2000.00');
        auth()->logout();
        $this->get($url)->assertRedirect(route('login'));
    }
}
